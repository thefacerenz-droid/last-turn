import { expect,test } from '@playwright/test';

test('a player can select, tune, drive, pause, save and revisit a run',async({page},info)=>{
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto('/');
  await expect(page.getByRole('button',{name:'Start driving',exact:true})).toBeVisible({timeout:60000});
  await page.locator('#loading').waitFor({state:'hidden'});
  await page.screenshot({path:info.outputPath('home.png')});
  await page.getByRole('button',{name:'Garage',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Aurelia CX'})).toBeVisible();
  await page.getByRole('button',{name:'Next car',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Kessel R4'})).toBeVisible();
  await page.getByRole('button',{name:'Customize',exact:true}).click();
  await page.getByRole('button',{name:'Paint #a13c2d',exact:true}).click();
  await page.getByLabel('Wheel design').selectOption('1');
  await page.mouse.move(960,370);await page.mouse.down();await page.mouse.move(1030,350,{steps:5});await page.mouse.up();
  await page.screenshot({path:info.outputPath('garage.png')});
  await page.getByRole('button',{name:'Map select',exact:true}).click();
  await page.locator('[data-route="marina"]').click();
  await page.getByRole('button',{name:'Use this route'}).click();
  await page.getByRole('button',{name:'Drive',exact:true}).click();
  await page.getByRole('button',{name:'Session setup',exact:true}).click();
  await page.getByLabel('Traffic density').selectOption('Custom');
  await page.getByLabel('Active vehicles').fill('36');
  await page.getByLabel('Lighting').selectOption('evening');
  await page.getByRole('button',{name:'Back',exact:true}).click();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Graphics preset').selectOption('Low');
  await page.getByLabel('Performance diagnostics').check();
  await page.getByRole('button',{name:'Driving',exact:true}).click();
  await page.getByLabel('Speed units').selectOption('KM/H');
  await page.getByRole('button',{name:'Back',exact:true}).click();
  await page.getByRole('button',{name:'Start driving',exact:true}).click();
  await expect(page.locator('#gear')).toBeVisible({timeout:60000});
  await page.keyboard.down('w');
  await expect.poll(async()=>Number(await page.locator('#speed').textContent()),{timeout:50000}).toBeGreaterThan(48);
  await page.keyboard.up('w');
  await expect(page.locator('#diagnostics')).toContainText('TRAFFIC 36');
  await expect(page.locator('#unit')).toHaveText('KM/H');
  await page.screenshot({path:info.outputPath('drive.png')});
  const telemetry=await page.locator('#diagnostics').innerText();
  console.log('Measured in browser\n'+telemetry);
  await page.keyboard.press('c');await expect(page.locator('#pass-notice')).toHaveText('Close chase');
  await page.keyboard.press('Escape');await expect(page.getByRole('button',{name:'Resume drive'})).toBeVisible();
  await page.getByRole('button',{name:'Resume drive'}).click();
  await page.keyboard.press('r');await expect(page.locator('#pass-notice')).toHaveText('Vehicle reset');
  await page.keyboard.press('Escape');await page.getByRole('button',{name:'Return to main menu'}).click();
  await page.getByRole('button',{name:'Records',exact:true}).click();
  await expect(page.locator('.record-list')).toContainText('Kessel R4');
  await page.reload();
  await expect(page.locator('.session-dock')).toContainText('Kessel R4');
  await expect(page.locator('.session-dock')).toContainText('36 active vehicles');
  await page.setViewportSize({width:740,height:480});await expect(page.getByRole('button',{name:'Start driving',exact:true})).toBeInViewport();
  expect(errors).toEqual([]);
});
